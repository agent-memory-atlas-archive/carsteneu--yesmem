// Generator creates and updates yesmem-ops.md files per project.
// Also serves as basis for AGENTS.md generation (via GenerateAgentsMd).
type Generator struct {
	store  *storage.Store
	client extraction.LLMClient
	cfg    *config.ClaudeMdConfig
}

func NewGenerator(store *storage.Store, client extraction.LLMClient, cfg *config.ClaudeMdConfig) *Generator {
	return &Generator{store: store, client: client, cfg: cfg}
}

// Generate creates or updates the yesmem-ops.md for the given project. The
// target sits in .claude/, where a hand-written file is possible as well, so
// the ownership rule applies here too (YM-266 / DEV-DT43).
func (g *Generator) Generate(projectShort, projectDir string) error {
	if err := outputFileError(g.cfg.OutputFileName); err != nil {
		return err
	}
	if err := ensureWritableDir(filepath.Join(projectDir, ".claude")); err != nil {
		return err
	}
	if err := ensureOwnedTarget(outputPathFor(projectDir, ".claude", g.cfg.OutputFileName)); err != nil {
		return err
	}
	return g.generate(projectShort, projectDir, ".claude", g.cfg.OutputFileName, claudeHeader)
}

// AgentsFileName is the opencode-convention target at the project root.
const AgentsFileName = "AGENTS.md"

// generatedMarker identifies a file yesmem wrote itself. AGENTS.md in the
// project root is usually hand-written, so the generator only overwrites files
// that carry this marker.
const generatedMarker = "Auto-generated by yesmem"

// legacyGeneratedMarker is the German marker yesmem wrote until afccf1df
// (2026-04-09). Those files are ours as well: refusing them would make every
// existing .claude/yesmem-ops.md unwritable by its own generator (YM-266).
const legacyGeneratedMarker = "Auto-generiert von yesmem"

// GenerateAgentsMd creates or updates AGENTS.md for the given project.
// Output goes to project root (opencode convention), neutral header (no Claude refs).
func (g *Generator) GenerateAgentsMd(projectShort, projectDir string) error {
	if err := ensureOwnedTarget(outputPathFor(projectDir, "", AgentsFileName)); err != nil {
		return err
	}
	return g.generate(projectShort, projectDir, "", AgentsFileName, agentsHeader)
}

// ensureOwnedTarget refuses to overwrite a file yesmem did not generate. A
// symlink at the target path is refused as well, so the write does not follow
// it to another file. Only regular files are read: opening a FIFO at the target
// waits for a writer that never comes and would hang the run (YM-341).
func ensureOwnedTarget(path string) error {
	info, err := os.Lstat(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("%s is a symlink, refusing to overwrite", path)
	}
	if !info.Mode().IsRegular() {
		return fmt.Errorf("%s is not a regular file, refusing to read it", path)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if ownedByYesmem(data) {
		return nil
	}
	return fmt.Errorf("%s exists and was not generated by yesmem, refusing to overwrite", path)
}

// ensureWritableDir refuses a directory that is a symlink. MkdirAll accepts one
// (it sees a directory) and the rename then writes through it, out of the
// project (YM-341). The window between this check and the rename stays open on
// purpose, on the single-user assumption this tool is built for: the same user
// who can swap .claude inside the project can write the target directly.
func ensureWritableDir(dir string) error {
	info, err := os.Lstat(dir)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("%s is a symlink, refusing to write through it", dir)
	}
	if !info.IsDir() {
		return fmt.Errorf("%s is not a directory, refusing to write into it", dir)
	}
	return nil
}

// outputFileError refuses a target name that is not a plain file name. The name
// comes from config.yaml (output_file); ".." in it moves the write out of the
// project directory, and a separator turns it into an unintended sub path
// (YM-341).
func outputFileError(fileName string) error {
	if fileName == "" {
		return nil // empty selects the default in outputPathFor
	}
	if fileName != filepath.Base(fileName) || fileName == "." || fileName == ".." {
		return fmt.Errorf("output_file %q must be a plain file name", fileName)
	}
	// SetupProject writes this name into CLAUDE.md and .gitignore, where a
	// newline would start a line of its own (YM-341).
	if strings.ContainsFunc(fileName, unicode.IsControl) {
		return fmt.Errorf("output_file %q must not contain control characters", fileName)
	}
	return nil
}

// ownedByYesmem reports whether the header names yesmem as the author. Only the
// first two lines count: the generated file starts with the title line followed
// by the marker line, and a hand-written file may quote the marker anywhere.
// Both header generations count, the English one and the German one yesmem
// wrote until afccf1df.
func ownedByYesmem(data []byte) bool {
	lines := strings.SplitN(string(data), "\n", 3)
	if len(lines) < 2 {
		return false
	}
	if !strings.Contains(lines[0], "Operational Notes") && !strings.Contains(lines[0], "Operative Hinweise") {
		return false
	}
	return strings.Contains(lines[1], generatedMarker) || strings.Contains(lines[1], legacyGeneratedMarker)
}

func claudeHeader(projectShort string, ts string) string {
	return fmt.Sprintf("# Operational Notes — %s\n> Auto-generated by yesmem (%s)\n> Do not edit manually — will be overwritten on changes\n\n", projectShort, ts)
}

func agentsHeader(projectShort string, ts string) string {
	return fmt.Sprintf("# Operational Notes — %s\n> Auto-generated by yesmem (%s)\n> Do not edit manually — will be overwritten on changes\n\n", projectShort, ts)
}

func (g *Generator) generate(projectShort, projectDir, subDir, fileName string, headerFn func(string, string) string) error {
	// 1. Collect
	learnings, err := g.store.GetLearningsForClaudeMd(projectShort, g.cfg.MaxPerCategory)
	if err != nil {
		return fmt.Errorf("collect learnings: %w", err)
	}
	if len(learnings) == 0 {
		return fmt.Errorf("no learnings for project %q", projectShort)
	}

	// 2. Deduplicate
	learnings = briefing.Deduplicate(learnings, 0.4)

	// 3. Change detection. One claudemd_state row per project serves both
	// output targets (yesmem-ops.md and AGENTS.md), so the hash alone does not
	// say whether THIS file is current. Alternating targets regenerate once per
	// switch, which is the price of the single row.
	hash := hashLearnings(learnings)
	outPath := outputPathFor(projectDir, subDir, fileName)
	state, err := g.store.GetClaudeMdState(projectShort)
	if err != nil {
		return fmt.Errorf("get state: %w", err)
	}
	if state != nil && state.LearningsHash == hash && filepath.Base(state.OutputPath) == filepath.Base(outPath) {
		return nil // nothing changed
	}

	// 4. Structure via LLM
	prompt, err := buildPrompt(projectShort, learnings)
	if err != nil {
		return err
	}
	content, err := g.client.Complete(systemPrompt, prompt)
	if err != nil {
		return fmt.Errorf("llm call: %w", err)
	}

	// 5. Write
	outputPath, err := g.writeTo(projectDir, subDir, fileName, projectShort, content, headerFn)
	if err != nil {
		return err
	}

	// 6. Save state
	return g.store.SaveClaudeMdState(&storage.ClaudeMdState{
		Project:       projectShort,
		LastGenerated: time.Now(),
		LearningsHash: hash,
		OutputPath:    outputPath,
	})
}

// NeedsRefresh checks if a project's file is stale.
func (g *Generator) NeedsRefresh(projectShort string) (bool, error) {
	return g.NeedsRefreshFor(projectShort, g.cfg.OutputFileName)
}

// NeedsRefreshFor reports whether the named output file is stale for the
// project. The target name matters because both file variants share one
// claudemd_state row.
func (g *Generator) NeedsRefreshFor(projectShort, fileName string) (bool, error) {
	if err := outputFileError(fileName); err != nil {
		return false, err
	}
	if fileName == "" {
		fileName = "yesmem-ops.md"
	}
	state, err := g.store.GetClaudeMdState(projectShort)
	if err != nil {
		return false, err
	}
	if state == nil {
		return true, nil
	}
	if filepath.Base(state.OutputPath) != fileName {
		return true, nil
	}
	learnings, err := g.store.GetLearningsForClaudeMd(projectShort, g.cfg.MaxPerCategory)
	if err != nil {
		return false, err
	}
	learnings = briefing.Deduplicate(learnings, 0.4)
	return hashLearnings(learnings) != state.LearningsHash, nil
}

func outputPathFor(projectDir, subDir, fileName string) string {
	if fileName == "" {
		fileName = "yesmem-ops.md"
	}
	if subDir == "" {
		return filepath.Join(projectDir, fileName)
	}
	return filepath.Join(projectDir, subDir, fileName)
}

func (g *Generator) writeTo(projectDir, subDir, fileName, projectShort, content string, headerFn func(string, string) string) (string, error) {
	if _, err := os.Stat(projectDir); os.IsNotExist(err) {
		return "", fmt.Errorf("project dir does not exist: %s", projectDir)
	}
	if err := outputFileError(fileName); err != nil {
		return "", err
	}
	if subDir != "" {
		dir := filepath.Join(projectDir, subDir)
		if err := ensureWritableDir(dir); err != nil {
			return "", err
		}
		if err := os.MkdirAll(dir, 0755); err != nil {
			return "", fmt.Errorf("create %s dir: %w", subDir, err)
		}
	}
	outPath := outputPathFor(projectDir, subDir, fileName)
	// The entry points check this too, to fail before the LLM call. Repeating it
	// here is what actually enforces the rule: this is the last point before the
	// rename, so the decision and the write sit together.
	if err := ensureOwnedTarget(outPath); err != nil {
		return "", err
	}
	header := headerFn(projectShort, time.Now().Format("2006-01-02 15:04"))
	return outPath, writeFileAtomic(outPath, []byte(header+strings.TrimSpace(content)+"\n"), 0644)
}

// writeFileAtomic replaces the target through a rename: a symlink or hardlink
// at the target name is replaced instead of followed, and a reader never sees a
// half-written file.
func writeFileAtomic(path string, data []byte, mode os.FileMode) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".yesmem-*.tmp")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	cleanup := func() { tmp.Close(); os.Remove(tmpName) }
	if _, err := tmp.Write(data); err != nil {
		cleanup()
		return err
	}
	if err := tmp.Close(); err != nil {
		os.Remove(tmpName)
		return err
	}
	if err := os.Chmod(tmpName, mode); err != nil {
		os.Remove(tmpName)
		return err
	}
	if err := os.Rename(tmpName, path); err != nil {
		os.Remove(tmpName)
		return err
	}
	return nil
}

func hashLearnings(learnings []models.Learning) string {
	h := sha256.New()
	for _, l := range learnings {
		fmt.Fprintf(h, "%d:%s\n", l.ID, l.Content)
	}
	return fmt.Sprintf("%x", h.Sum(nil))[:16]
}
